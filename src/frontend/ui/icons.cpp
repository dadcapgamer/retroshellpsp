void icon(gfx::Renderer& r, Icon which, float x, float y, u32 color) {
    const int idx = int(which);
    if (idx < 0 || idx >= int(Icon::Count)) return;
    const char* art = ART[idx];
    x = float(int(x));
    y = float(int(y));
    for (int row = 0; row < N; row++) {
        int col = 0;
        while (col < N) {
            while (col < N && art[row * N + col] != '#') col++;
            const int start = col;
            while (col < N && art[row * N + col] == '#') col++;
            if (col > start)
                r.rect(x + float(start), y + float(row), float(col - start),
                       1.f, color);
        }
    }
}

